// .dev/floor/check-capability-catalog.test.mjs — hermetic tests for the drift checker + the CLIs.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, appendFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { checkCatalog, checkReadmeCurrentState } from "./check-capability-catalog.mjs";
import { generate } from "./gen-capability-catalog.mjs";
import { OUT_DIR, README_PATH } from "./capability-catalog-core.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const MARK_BEGIN =
  "<!-- CURRENT-STATE:BEGIN — GENERATED by .dev/floor/gen-capability-catalog.mjs. DO NOT EDIT BETWEEN MARKERS. Regenerate: npm run docs:generate -->";
const MARK_END = "<!-- CURRENT-STATE:END -->";

function makeRepo() {
  return mkdtempSync(join(tmpdir(), "pharn-cat-check-"));
}
function cap(root, dirRel, base, fm, body) {
  const dir = join(root, dirRel);
  mkdirSync(dir, { recursive: true });
  const fmLines = Object.entries(fm).map(([k, v]) => `${k}: ${Array.isArray(v) ? `[${v.map((x) => `"${x}"`).join(", ")}]` : v}`);
  writeFileSync(join(dir, `${base}.md`), `---\n${fmLines.join("\n")}\n---\n\n${body}\n`);
}
// The checker now covers TWO artifacts, so the fixture repo must carry the surface the README block
// enumerates as well as the capabilities the catalog enumerates.
function seed(root, { readme = `# Fixture\n\nIntro.\n\n${MARK_BEGIN}\n\n${MARK_END}\n\nTail.\n` } = {}) {
  cap(
    root,
    "pharn/pharn-review/aaa",
    "aaa",
    { name: "aaa", role: "lens", kind: "pharn-owned", version: "0.1.0", applies: ["universal"] },
    "# aaa — flags aaa"
  );
  cap(
    root,
    "pharn/pharn-pipeline/grillers/gg",
    "gg",
    { name: "gg", role: "griller", kind: "pharn-owned", version: "0.1.0", applies: ["universal"] },
    "# gg — asks gg"
  );
  const put = (rel, names, body) => {
    mkdirSync(join(root, rel), { recursive: true });
    for (const n of names) writeFileSync(join(root, rel, n), body);
  };
  put("pharn/pharn-contracts", ["finding-shape.md"], "# a contract\n");
  put(".claude/commands", ["pharn-spec.md", "pharn-dev-plan.md"], "# a command\n");
  put(".claude/hooks", ["protect-trusted-paths.cjs"], "// a hook\n");
  put("pharn/floor", ["validate.mjs", "validate.test.mjs"], "// a checker\n");
  if (readme !== null) writeFileSync(join(root, README_PATH), readme);
}

test("clean: after generate, checkCatalog is GREEN (ok, no findings)", () => {
  const root = makeRepo();
  try {
    seed(root);
    const { written } = generate(root);
    assert.equal(written, 3); // README + 2 pages
    const { ok, findings } = checkCatalog(root);
    assert.equal(ok, true);
    assert.deepEqual(findings, []);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("drift: mutating a committed page → RED with a DRIFT finding", () => {
  const root = makeRepo();
  try {
    seed(root);
    generate(root);
    appendFileSync(join(root, OUT_DIR, "aaa.md"), "tampered\n");
    const { ok, findings } = checkCatalog(root);
    assert.equal(ok, false);
    assert.ok(findings.some((f) => f.type === "DRIFT" && f.file === `${OUT_DIR}/aaa.md`));
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

