test("README drift: hand-editing a MARKER line is itself drift (markers are inside the guarded region)", () => {
  const root = makeRepo();
  try {
    seed(root);
    generate(root);
    const text = readFileSync(join(root, README_PATH), "utf8");
    writeFileSync(join(root, README_PATH), text.replace("DO NOT EDIT BETWEEN MARKERS.", "edit freely."));
    assert.ok(checkReadmeCurrentState(root).some((f) => f.type === "README_DRIFT"));
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("README markers: missing, duplicated, and inverted each → RED README_MARKERS naming the defect", () => {
  const cases = [
    ["# F\n\nno markers\n", /no <!-- CURRENT-STATE:BEGIN/],
    [`# F\n\n${MARK_BEGIN}\n\nbody\n`, /no <!-- CURRENT-STATE:END/],
    [`# F\n\n${MARK_BEGIN}\n${MARK_END}\n\n${MARK_BEGIN}\n${MARK_END}\n`, /2 BEGIN markers found/],
    [`# F\n\n${MARK_END}\n\n${MARK_BEGIN}\n`, /inverted/],
  ];
  for (const [readme, expected] of cases) {
    const root = makeRepo();
    try {
      seed(root, { readme });
      const findings = checkReadmeCurrentState(root);
      assert.equal(findings.length, 1);
      assert.equal(findings[0].type, "README_MARKERS");
      assert.match(findings[0].problem, expected);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }
});

test("README missing entirely → RED README_MISSING (fail-closed, never a silent GREEN)", () => {
  const root = makeRepo();
  try {
    seed(root, { readme: null });
    const findings = checkReadmeCurrentState(root);
    assert.deepEqual(
      findings.map((f) => f.type),
      ["README_MISSING"]
    );
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("README: an enumeration failure surfaces as ENUM_ERROR, not a crash and not a pass", () => {
  const root = makeRepo();
  try {
    seed(root);
    generate(root);
    rmSync(join(root, ".claude/hooks"), { recursive: true, force: true });
    const findings = checkReadmeCurrentState(root);
    assert.equal(findings.length, 1);
    assert.equal(findings[0].type, "ENUM_ERROR");
    assert.match(findings[0].problem, /expected directory is missing or unreadable/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("CLI: README drift alone is enough to exit 1, with the fix command printed", () => {
  const root = makeRepo();
  try {
    seed(root);
    generate(root);
    const text = readFileSync(join(root, README_PATH), "utf8");
    writeFileSync(join(root, README_PATH), text.replace("Contracts — 1", "Contracts — 7"));

    const run = spawnSync("node", [join(HERE, "check-capability-catalog.mjs"), root], { encoding: "utf8" });
    assert.equal(run.status, 1);
    assert.match(run.stdout, /CATALOG: RED/);
    assert.match(run.stdout, /README_DRIFT/);
    assert.match(run.stdout, /npm run docs:generate/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
